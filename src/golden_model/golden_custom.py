SHIFT = 8      # output quantization: ReLU, then >> SHIFT, then saturate to 255

assert img.shape == (16,16) and kers.shape == (3,3,3)

def conv(a, k):
    return np.array([[(a[r:r+3, c:c+3] * k).sum() for c in range(14)] for r in range(14)])

def pool(m):
    return m.reshape(7,2,7,2).max(axis=(1,3))

conv_o = [conv(img, k) for k in kers]
pool_o = [pool(m) for m in conv_o]
relu_o = [np.clip(m >> SHIFT, 0, 255) for m in pool_o]   # negatives -> 0

