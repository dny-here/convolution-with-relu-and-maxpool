    print(f"=== Channel {c+1} ===")
    print("conv (14x14), min/max =", conv_o[c].min(), conv_o[c].max()); print(conv_o[c])
    print("maxpool (7x7):");  print(pool_o[c])
    print("relu+sat (7x7):"); print(relu_o[c])

